# ## 92. クラス３（オーバーライド）
# 以下の要件に従って、クラスの継承を実装してください。
# * 基底クラスとして `Animal` を定義し、`__init__` メソッドで名前を初期化する。
# * `speak` メソッドを定義し、「[名前] is making a sound」と出力する。
# * `Animal` クラスを継承する Dog クラスを定義し、`speak` メソッドをオーバーライドして、「[名前] says Woof!」と出力する。
